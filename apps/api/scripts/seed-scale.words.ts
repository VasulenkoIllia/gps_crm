export interface WordList {
  shown: string[];
  norm: string[];
}

// The SQL of the seed puts names together from these words, so each word comes with its `*_norm` form already made by
// the same function as the app's: a name of normalized words joined by one space is normalized as a whole
function listOf(words: string[]): WordList {
  return { shown: words, norm: words.map(normalizeName) };
}

